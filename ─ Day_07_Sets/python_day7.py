print("========== DAY 07 - PYTHON SETS ==========\n")

# ----------------------------------------------------------
# 1. Creating Sets
# ----------------------------------------------------------

print("1. Creating Sets")

fruits = {"Apple", "Banana", "Orange"}

numbers = {10, 20, 30, 40, 50}

student = {"Chandan", 26, 89.5, True}

print(fruits)
print(numbers)
print(student)


# ----------------------------------------------------------
# 2. Duplicate Values
# ----------------------------------------------------------

print("\n2. Duplicate Values")

duplicate_numbers = {1, 2, 2, 3, 4, 4, 5}

print(duplicate_numbers)


# ----------------------------------------------------------
# 3. Length
# ----------------------------------------------------------

print("\n3. Length")

print(len(fruits))


# ----------------------------------------------------------
# 4. Loop Through Set
# ----------------------------------------------------------

print("\n4. Loop")

for fruit in fruits:
    print(fruit)


# ----------------------------------------------------------
# 5. Membership
# ----------------------------------------------------------

print("\n5. Membership")

print("Apple" in fruits)
print("Kiwi" in fruits)


# ----------------------------------------------------------
# 6. Add Item
# ----------------------------------------------------------

print("\n6. add()")

fruits.add("Mango")

print(fruits)


# ----------------------------------------------------------
# 7. Update Set
# ----------------------------------------------------------

print("\n7. update()")

more_fruits = {"Kiwi", "Pineapple"}

fruits.update(more_fruits)

print(fruits)


# ----------------------------------------------------------
# 8. Remove Item
# ----------------------------------------------------------

print("\n8. remove()")

fruits.remove("Banana")

print(fruits)


# ----------------------------------------------------------
# 9. Discard Item
# ----------------------------------------------------------

print("\n9. discard()")

fruits.discard("Orange")

print(fruits)


# ----------------------------------------------------------
# 10. Pop
# ----------------------------------------------------------

print("\n10. pop()")

removed_item = fruits.pop()

print("Removed:", removed_item)

print(fruits)


# ----------------------------------------------------------
# 11. Copy
# ----------------------------------------------------------

print("\n11. copy()")

copy_set = fruits.copy()

print(copy_set)


# ----------------------------------------------------------
# 12. Clear
# ----------------------------------------------------------

print("\n12. clear()")

colors = {"Red", "Blue", "Green"}

colors.clear()

print(colors)


# ----------------------------------------------------------
# 13. Union
# ----------------------------------------------------------

print("\n13. union()")

set1 = {1,2,3}

set2 = {3,4,5}

print(set1.union(set2))


# ----------------------------------------------------------
# 14. Intersection
# ----------------------------------------------------------

print("\n14. intersection()")

print(set1.intersection(set2))


# ----------------------------------------------------------
# 15. Difference
# ----------------------------------------------------------

print("\n15. difference()")

print(set1.difference(set2))

print(set2.difference(set1))


# ----------------------------------------------------------
# 16. Symmetric Difference
# ----------------------------------------------------------

print("\n16. symmetric_difference()")

print(set1.symmetric_difference(set2))


# ----------------------------------------------------------
# 17. Remove Duplicates
# ----------------------------------------------------------

print("\n17. Remove Duplicates")

marks = [85,90,85,95,90,88]

unique_marks = set(marks)

print(unique_marks)


print("\n========== DAY 07 COMPLETED ==========")